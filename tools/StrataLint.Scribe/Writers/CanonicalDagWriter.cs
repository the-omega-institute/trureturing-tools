using System.Collections.Immutable;
using System.Globalization;
using System.Text;
using System.Text.Json;
using StrataLint.Engine;
using Trureturing.Truth;

namespace StrataLint.Scribe;

/// Renders the repository truth DAG as a canonical Markdown projection.
///
/// The graph projection is assembled by Scribe (TruthDagProjection); this writer only renders it,
/// exactly as CanonicalMarkdownWriter projects Scribe documents and FileMapProjectionWriter
/// projects Meta/FILEMAP.toml. It derives nothing: node state, graph depth, edge direction and the
/// content address all come from the capability, so the picture cannot disagree with the harness.
///
/// Mermaid vertex identifiers are positional (n0, n1, ...) over the DAG's ordinal node order rather
/// than escaped repository paths: escaping is not injective (A/B.lean and A_B.lean collapse under
/// separator replacement) and a collision would silently merge two truth nodes into one vertex.
public static class CanonicalDagWriter
{
    private static readonly UTF8Encoding StrictUtf8 = new(false, true);
    private const string OmegaOnlyBadge = "「仅 Omega · 零公理」";

    public static ImmutableArray<byte> Write(TruthDagProjection dag) => Write(dag, null);

    internal static ImmutableArray<byte> Write(TruthDagProjection dag, TruthGraphSection? graph)
    {
        ArgumentNullException.ThrowIfNull(dag);

        var nodes = dag.Nodes;
        var identifiers = nodes
            .Select(static (node, index) => (node.RepoPath, Id: "n" + index.ToString(CultureInfo.InvariantCulture)))
            .ToImmutableDictionary(static item => item.RepoPath, static item => item.Id);

        var builder = new StringBuilder();
        AppendPreamble(builder, dag, nodes);
        AppendGraph(builder, dag, nodes, identifiers);
        AppendBlockers(builder, dag);
        var markedDeclarations = graph?.Nodes.Where(static node => node.OmegaOnlyAxiomFreeDeclarations is { IsEmpty: false })
            .ToDictionary(static node => node.RepoPath, static node => node.OmegaOnlyAxiomFreeDeclarations!.Value,
                StringComparer.Ordinal);
        var pairedDeclarations = graph?.Nodes.Where(static node => node.StrictOmegaDeclarations is { IsEmpty: false })
            .ToDictionary(static node => node.RepoPath, static node => node.StrictOmegaDeclarations!.Value,
                StringComparer.Ordinal);
        AppendNodesByDepth(builder, dag, nodes, markedDeclarations, pairedDeclarations);
        return ImmutableArray.CreateRange(StrictUtf8.GetBytes(builder.ToString()));
    }

    private static void AppendPreamble(
        StringBuilder builder,
        TruthDagProjection dag,
        ImmutableArray<TruthProjectionNode> nodes)
    {
        builder.Append("# Truth DAG\n\n")
            .Append("<!-- Generated by DagEmitter from the repository truth DAG. Do not edit. -->\n\n")
            .Append("- root: `")
            .Append(dag.RootSha256)
            .Append("`\n- nodes: ")
            .Append(Count(nodes.Length))
            .Append(" total")
            .Append("\n- edges: ")
            .Append(Count(dag.Edges.Length))
            .Append("\n- open blockers: ")
            .Append(Count(dag.OpenBlockers.Length))
            .Append("\n- max depth: ")
            .Append(Count(MaxDepth(dag, nodes)))
            .Append("\n- states: ");
        var census = Enum.GetValues<TruthState>()
            .Select(state => Name(state)
                + " "
                + Count(nodes.Count(node => node.State == state)));
        builder.AppendJoin(" | ", census).Append("\n\n");
    }

    private static void AppendGraph(
        StringBuilder builder,
        TruthDagProjection dag,
        ImmutableArray<TruthProjectionNode> nodes,
        ImmutableDictionary<RepoPath, string> identifiers)
    {
        builder.Append("## Graph\n\n```mermaid\nflowchart TD\n");

        // Every class is declared unconditionally: a reader comparing two revisions should see the
        // legend stay put rather than appear and vanish with the census.
        foreach (var state in Enum.GetValues<TruthState>())
        {
            builder.Append("  classDef ")
                .Append(Name(state))
                .Append(' ')
                .Append(Style(state))
                .Append('\n');
        }

        foreach (var node in nodes)
        {
            builder.Append("  ")
                .Append(identifiers[node.RepoPath])
                .Append("[\"")
                .Append(Label(node.RepoPath.Value))
                .Append("\"]:::")
                .Append(Name(node.State))
                .Append('\n');
        }

        foreach (var edge in dag.Edges)
        {
            builder.Append("  ")
                .Append(identifiers[edge.Dependency])
                .Append(" --> ")
                .Append(identifiers[edge.Dependent])
                .Append('\n');
        }

        builder.Append("```\n\n");
    }

    private static void AppendBlockers(StringBuilder builder, TruthDagProjection dag)
    {
        builder.Append("## Open dependency blockers\n\n");
        if (dag.OpenBlockers.IsEmpty)
        {
            builder.Append("None.\n\n");
            return;
        }

        // A managed import with no node behind it is a hole in the graph. Listing it keeps the
        // picture honest: the flowchart above shows no edge there, and this says why.
        foreach (var blocker in dag.OpenBlockers)
        {
            builder.Append("- `")
                .Append(blocker.Dependent.Value)
                .Append("` imports `")
                .Append(blocker.DependencyModule)
                .Append("`, which this snapshot does not carry\n");
        }

        builder.Append('\n');
    }

    private static void AppendNodesByDepth(
        StringBuilder builder,
        TruthDagProjection dag,
        ImmutableArray<TruthProjectionNode> nodes,
        IReadOnlyDictionary<string, ImmutableArray<TruthGraphDeclaration>>? markedDeclarations,
        IReadOnlyDictionary<string, ImmutableArray<TruthExportDeclaration>>? pairedDeclarations)
    {
        builder.Append("## Nodes by depth\n\n");
        if (nodes.IsEmpty)
        {
            builder.Append("None.\n");
            return;
        }

        if (markedDeclarations is { Count: > 0 })
        {
            builder.Append(OmegaOnlyBadge)
                .Append(" reflects the last frozen measurement for the declaration and statement pin. "
                    + "A later proof edit can retain that pin.\n\n");
        }

        if (pairedDeclarations is { Count: > 0 })
            builder.Append("Official and strict Omega arrays describe the paired frozen measurements at their recorded statement pins.\n\n");

        var groups = nodes
            .GroupBy(node => dag.Depth(node.RepoPath))
            .OrderBy(static group => group.Key);
        foreach (var group in groups)
        {
            builder.Append("### depth ")
                .Append(Count(group.Key))
                .Append("\n\n");
            foreach (var node in group)
            {
                builder.Append("- `")
                    .Append(node.RepoPath.Value)
                    .Append("` — ")
                    .Append(Name(node.State))
                    .Append(" — ")
                    .Append(node.Gid is null ? "no GID" : "`" + node.Gid.Value + "`")
                    .Append('\n');
                if (markedDeclarations is not null && markedDeclarations.TryGetValue(node.RepoPath.Value, out var declarations))
                {
                    foreach (var declaration in declarations)
                    {
                        builder.Append("  - ");
                        AppendCodeSpan(builder, DeclarationName(declaration.DeclarationNameKey));
                        builder.Append(" (").Append(declaration.Kind).Append(") ").Append(OmegaOnlyBadge).Append('\n');
                    }
                }
                if (pairedDeclarations is not null && pairedDeclarations.TryGetValue(node.RepoPath.Value, out var pairs))
                {
                    foreach (var declaration in pairs)
                    {
                        var strict = declaration.StrictOmega!;
                        builder.Append("  - ");
                        AppendCodeSpan(builder, DeclarationName(declaration.DeclarationNameKey));
                        builder.Append(" (").Append(declaration.Kind).Append(") — official libraries ");
                        AppendCodeSpan(builder, JsonSerializer.Serialize(declaration.Libraries!.Value));
                        builder.Append(", official axioms ");
                        AppendCodeSpan(builder, JsonSerializer.Serialize(declaration.Axioms!.Value));
                        builder.Append(" — strict Omega backend libraries ");
                        AppendCodeSpan(builder, JsonSerializer.Serialize(strict.Libraries));
                        builder.Append(", strict Omega backend axioms ");
                        AppendCodeSpan(builder, JsonSerializer.Serialize(strict.Axioms));
                        builder.Append('\n');
                    }
                }
            }

            builder.Append('\n');
        }

        builder.Length -= 1;
    }

    private static string DeclarationName(string nameKey)
    {
        var components = CanonicalLeanNameDecoder.ComponentsPrefix(nameKey, 0, out _);
        var spelling = new StringBuilder();
        foreach (var (kind, value) in components)
        {
            if (spelling.Length > 0) spelling.Append('.');
            if (kind == "nn")
            {
                spelling.Append(value);
                continue;
            }

            var first = true;
            var unquoted = value.Length > 0;
            foreach (var rune in value.EnumerateRunes())
            {
                var character = rune.Value;
                var identifier = IsIdentifierStart(character) || (!first && IsIdentifierSuffix(character));
                // A JSON string of the full key preserves delimiters, whitespace, and controls.
                if (!identifier && character is not (>= '!' and <= '~'))
                    return JsonSerializer.Serialize(nameKey);
                unquoted &= identifier;
                first = false;
            }

            if (unquoted) spelling.Append(value);
            else spelling.Append('«').Append(value).Append('»');
        }

        return spelling.ToString();
    }

    // Lean's letter-like and subscript ranges keep ordinary identifiers readable.
    private static bool IsIdentifierStart(int character) => character is
        (>= 'A' and <= 'Z') or (>= 'a' and <= 'z') or '_'
        or (>= 0x00c0 and <= 0x00ff and not (0x00d7 or 0x00f7)) or (>= 0x0100 and <= 0x017f)
        or (>= 0x0391 and <= 0x03a9 and not (0x03a0 or 0x03a3))
        or (>= 0x03b1 and <= 0x03c9 and not 0x03bb) or (>= 0x03ca and <= 0x03fb)
        or (>= 0x1f00 and <= 0x1ffe) or (>= 0x2100 and <= 0x214f) or (>= 0x1d49c and <= 0x1d59f);

    private static bool IsIdentifierSuffix(int character) => character is
        (>= '0' and <= '9') or '\'' or '!' or '?'
        or (>= 0x2080 and <= 0x2089) or (>= 0x2090 and <= 0x209c) or (>= 0x1d62 and <= 0x1d6a) or 0x2c7c;

    private static void AppendCodeSpan(StringBuilder builder, string text)
    {
        if (!text.Contains('`'))
        {
            builder.Append('`').Append(text).Append('`');
            return;
        }

        // Character references keep arbitrary backtick runs and punctuation literal in GFM.
        builder.Append("<code>");
        foreach (var rune in text.EnumerateRunes())
            builder.Append("&#").Append(rune.Value.ToString(CultureInfo.InvariantCulture)).Append(';');
        builder.Append("</code>");
    }

    private static int MaxDepth(TruthDagProjection dag, ImmutableArray<TruthProjectionNode> nodes) =>
        nodes.IsEmpty ? 0 : nodes.Max(node => dag.Depth(node.RepoPath));

    private static string Count(int value) => value.ToString(CultureInfo.InvariantCulture);

    private static string Name(TruthState state) => state switch
    {
        TruthState.Closed => "closed",
        TruthState.Open => "open",
        TruthState.Tail => "tail",
        TruthState.Semantic => "semantic",
        _ => throw new ArgumentOutOfRangeException(nameof(state), state, "unknown truth state"),
    };

    private static string Style(TruthState state) => state switch
    {
        TruthState.Closed => "fill:#dcfce7,stroke:#166534,color:#052e16",
        TruthState.Open => "fill:#fef9c3,stroke:#854d0e,color:#1c1917",
        TruthState.Tail => "fill:#fee2e2,stroke:#991b1b,color:#450a0a",
        TruthState.Semantic => "fill:#e5e7eb,stroke:#374151,color:#111827",
        _ => throw new ArgumentOutOfRangeException(nameof(state), state, "unknown truth state"),
    };

    /// Mermaid ends a quoted label at the first unescaped quote. Repository paths cannot contain
    /// one today, so this is a guard against a future path shape silently truncating the graph.
    private static string Label(string value) => value.Replace("\"", "#quot;", StringComparison.Ordinal);
}
